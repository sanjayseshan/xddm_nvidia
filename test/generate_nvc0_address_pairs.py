#!/usr/bin/env python3
"""Generate the external NVC0 direct-address method inventory from Mesa headers."""

import argparse
import re
from pathlib import Path


SOURCES = {
    "nvc0_3d.xml.h": 0,
    "nvc0_m2mf.xml.h": 2,
    "nve4_p2mf.xml.h": 2,
    "nve4_copy.xml.h": 4,
}
INDEX_COUNTS = {"GV100_3D_SP": 6}

DEFINE_RE = re.compile(
    r"^#define\s+(\w+?_(?:ADDRESS|START)_(?:HIGH|LOW))"
    r"(?:\([^)]*\))?\s+(.+?)\s*$"
)
CONST_RE = re.compile(r"^\(?\s*(0x[0-9a-fA-F]+)\s*\)?$")
ARRAY_RE = re.compile(
    r"^\(?\s*(0x[0-9a-fA-F]+)\s*\+\s*"
    r"(0x[0-9a-fA-F]+)\s*\*\s*\(i0\)\s*\)?$"
)


def access_for(name):
    if "_START" in name:
        return "NVX_3D_RELOC_READ"
    if "_COND_ADDRESS" in name or "_SRC_ADDRESS" in name or "_CODE_ADDRESS" in name:
        return "NVX_3D_RELOC_READ"
    if "_OFFSET_IN_" in name:
        return "NVX_3D_RELOC_READ"
    if "_DST_ADDRESS" in name or "_QUERY_ADDRESS" in name:
        return "NVX_3D_RELOC_WRITE"
    if "_OFFSET_OUT_" in name:
        return "NVX_3D_RELOC_WRITE"
    if "_TFB_ADDRESS" in name or "_VERTEX_RUNOUT_ADDRESS" in name:
        return "NVX_3D_RELOC_WRITE"
    if "_CLIPID_ADDRESS" in name or "_VERTEX_QUARANTINE_ADDRESS" in name:
        return "NVX_3D_RELOC_WRITE"
    if ("_RT_ADDRESS" in name or "_ZETA_ADDRESS" in name or
            "_ZCULL_ADDRESS" in name or "_IMAGE_ADDRESS" in name):
        return "(NVX_3D_RELOC_READ | NVX_3D_RELOC_WRITE)"
    if "_SP_ADDRESS" in name:
        return "NVX_3D_RELOC_READ"
    if "_TEMP_ADDRESS" in name:
        return "(NVX_3D_RELOC_READ | NVX_3D_RELOC_WRITE)"
    if "_TSC_ADDRESS" in name or "_TIC_ADDRESS" in name or "_CB_ADDRESS" in name:
        return "NVX_3D_RELOC_READ"
    raise ValueError(f"unclassified address method: {name}")


def parse_expr(expr):
    match = CONST_RE.match(expr)
    if match:
        return int(match.group(1), 16), 0
    match = ARRAY_RE.match(expr)
    if match:
        return int(match.group(1), 16), int(match.group(2), 16)
    raise ValueError(f"unrecognized method expression: {expr}")


def render(mesa_root):
    rows = []
    for filename, subchannel in SOURCES.items():
        path = mesa_root / "src/gallium/drivers/nouveau/nvc0" / filename
        lines = path.read_text(encoding="utf-8").splitlines()
        defines = {}
        lengths = {}
        for line in lines:
            match = DEFINE_RE.match(line)
            if match:
                name, expr = match.groups()
                stem, side = name.rsplit("_", 1)
                defines.setdefault(stem, {})[side] = parse_expr(expr)
                continue
            match = re.match(r"^#define\s+(\w+)__LEN\s+(0x[0-9a-fA-F]+)\s*$", line)
            if match:
                lengths[match.group(1)] = int(match.group(2), 16)

        for stem, pair in defines.items():
            if set(pair) != {"HIGH", "LOW"}:
                raise ValueError(f"incomplete address pair {filename}:{stem}")
            high, high_stride = pair["HIGH"]
            low, low_stride = pair["LOW"]
            if high_stride != low_stride:
                raise ValueError(f"stride mismatch for {stem}")
            if stem.endswith("_START"):
                group = stem + "_HIGH"
            else:
                group = stem.rsplit("_ADDRESS", 1)[0]
            count = lengths.get(group, INDEX_COUNTS.get(
                group, 1 if high_stride == 0 else None))
            if count is None:
                raise ValueError(f"missing array length for {stem}")
            rows.append((subchannel, high, low, high_stride, count,
                         access_for(stem)))

    rows.sort()
    seen = set()
    for row in rows:
        key = row[:5]
        if key in seen:
            raise ValueError(f"duplicate address pair: {row}")
        seen.add(key)

    result = [
        "/* Generated by test/generate_nvc0_address_pairs.py; do not edit. */",
        "#ifndef NVX_NVC0_ADDRESS_PAIRS_H",
        "#define NVX_NVC0_ADDRESS_PAIRS_H",
        "",
        "typedef struct NVX_3D_NVC0_ADDRESS_PAIR {",
        "    uint32_t Subchannel;",
        "    uint32_t HighMethod;",
        "    uint32_t LowMethod;",
        "    uint32_t IndexStride;",
        "    uint32_t IndexCount;",
        "    uint32_t Access;",
        "} NVX_3D_NVC0_ADDRESS_PAIR;",
        "",
        "static const NVX_3D_NVC0_ADDRESS_PAIR Nvx3dNvc0AddressPairs[] = {",
    ]
    for subchannel, high, low, stride, count, access in rows:
        result.append(
            f"    {{{subchannel}U, 0x{high:04x}U, 0x{low:04x}U, "
            f"0x{stride:04x}U, {count}U, {access}}},"
        )
    result.extend([
        "};",
        "#define NVX_3D_NVC0_ADDRESS_PAIR_COUNT "
        "((uint32_t)(sizeof(Nvx3dNvc0AddressPairs) / sizeof(Nvx3dNvc0AddressPairs[0])))",
        "",
        "#endif",
        "",
    ])
    return "\n".join(result)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("mesa_root", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(args.mesa_root)
    if args.check:
        existing = args.output.read_text(encoding="utf-8")
        if existing != generated:
            raise SystemExit(f"stale generated address inventory: {args.output}")
    else:
        args.output.write_text(generated, encoding="utf-8")
    row_count = sum(line.startswith("    {") for line in generated.splitlines())
    print(f"NVC0 direct-address method pairs: {row_count}")


if __name__ == "__main__":
    main()
